# --------------------------------------------------------------------------- #
# 5. Planner system prompt — the exact text the LLM receives so it TRANSLATES a
#    free-form customer command into an executable scene_plan. Fed alongside the
#    ingested product data. Output is validated against the scene_plan schema.
# --------------------------------------------------------------------------- #

PLANNER_SYSTEM_PROMPT = """\
You are the video-planning brain of Easy Life's video agent. A small-business
owner gives you a short brief (usually in Hebrew) and you already have their REAL
product data (name, description, image URLs, brand palette) crawled from their
store. Your job is to translate that into a precise, executable 3-scene plan for
a CINEMATIC, photorealistic vertical (9:16) ad — the quality bar is a modern
premium commercial, never motion-graphics over a gradient.

Rules:
- Exactly 3 scenes, in fixed order: hook, product, cta.
- Ground every scene in the customer's ACTUAL product photo (pass its image id as
  the keyframe reference). Never invent a different product.
- For each scene emit:
    role            one of: hook | product | cta
    model           the Higgsfield video model id (default "seedance_2_0")
    keyframe_prompt a photorealistic still description for the product-photoshoot
                    step — describe product, setting, lighting, framing.
    video_prompt    the MOTION the camera and subject make — draw camera terms
                    ONLY from the approved camera vocabulary; describe subject
                    motion (steam rises, gold dust falls, glaze drips).
    camera          the camera-move key(s) you used (from CAMERA_MOVES).
    duration        seconds (hook ~3, product ~5, cta ~4).
- Lighting and look terms must come from the approved LIGHTING / LOOK vocabulary.
- NEVER put on-screen text, price, logo, or a call-to-action INTO the video_prompt
  or keyframe_prompt. Those are overlaid later by the branding layer. Note the CTA
  copy separately in `overlay_text` on the cta scene.
- Keep the product's shape, color and label faithful; prefer medium/angled framing
  over close-ups of small printed text (video models garble text).

Return ONLY the scene_plan JSON.
"""


def build_scene_prompt(role: str, product_name: str, style_hint: str = "") -> dict:
    """Deterministic fallback plan for one scene when the LLM is unavailable.

    Produces a sensible keyframe + video prompt from the role template so the
    pipeline can run (and be tested) without a live LLM call. The LLM planner
    normally overrides this with a richer, product-specific plan.
    """
    tpl = SCENE_ROLE_TEMPLATES[role]
    camera_key = tpl["camera"][0]
    lighting = LIGHTING[0]
    look = ", ".join(LOOK[:3])
    keyframe = (
        f"Cinematic advertising product photograph of {product_name}, "
        f"{lighting}, {look}. {style_hint} {PROMPT_GUARDRAILS}"
    ).strip()
    video = (
        f"{CAMERA_MOVES[camera_key]}, {lighting}, {look}. {PROMPT_GUARDRAILS}"
    )
    return {
        "role": role,
        "model": tpl["video_model"],
        "camera": [camera_key],
        "keyframe_prompt": keyframe,
        "video_prompt": video,
        "duration": tpl["duration_s"],
        **({"overlay_text": None} if role == "cta" else {}),
    }


def default_plan(product_name: str, style_hint: str = "") -> list[dict]:
    """A full 3-scene deterministic plan — the no-LLM fallback and the test fixture."""
    return [build_scene_prompt(role, product_name, style_hint) for role in ("hook", "product", "cta")]
