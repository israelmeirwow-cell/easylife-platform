"""The video agent's generation intelligence — how a customer command becomes
a cinematic reel.

This module is the agent's KNOWLEDGE, not a renderer. It encodes what we learned
from the Higgsfield skill set (higgsfield-generate / product-photoshoot) so the
planner LLM and the provider layer agree on:

  1. which Higgsfield model to use for each job (MODEL_ROUTING / VIDEO_MODELS /
     IMAGE_MODELS),
  2. the controlled vocabulary for cinematic direction (CAMERA_MOVES / LIGHTING /
     LOOK) — so prompts read like a DP's shot list, not amateur text,
  3. what each of the 3 scene roles should look like (SCENE_ROLE_TEMPLATES),
  4. the end-to-end pipeline that turns "make me a video for X" into shots
     (PIPELINE), and
  5. the exact instruction block the planner LLM receives (PLANNER_SYSTEM_PROMPT),
     which makes it emit a structured scene_plan the provider can execute.

DESIGN DECISION (2026-07-22, supersedes the HyperFrames-as-engine draft):
The cinematic footage is generated by **Higgsfield image-to-video** conditioned
on the customer's REAL product photos (crawled from their site). HyperFrames is
demoted to the OVERLAY/branding/stitch layer only — video models render bad text,
so captions, logo, price and the CTA end-card are composited by HyperFrames on
top of the cinematic clips. The quality bar is a realistic, cinematic ad with
professional camera moves — never motion-graphics-over-a-gradient.
"""

